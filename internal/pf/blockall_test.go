const blockAllRules = `# Generated by leakguard. Do not edit; run "leakguard enable" instead.
# Protected services: anthropic, example
table <leakguard> const persist { 160.79.104.0/23, 38.46.212.0/24, 2607:6bc0::/48, 203.0.113.0/24, 2001:db8::/32 }
block return out quick to <leakguard>
`

// S7: an empty VPN means no interface may carry protected traffic: only the
// block rule is rendered.
func TestRulesWithoutAVPNBlockEveryInterface(t *testing.T) {
	if got := mustRules(t, ""); got != blockAllRules {
		t.Fatalf("Rules(\"\") =\n%s\nwant\n%s", got, blockAllRules)
	}
}

// S7: Apply("") loads the block rule only and verifies it.
func TestApplyWithoutAVPNLoadsOnlyTheBlockRule(t *testing.T) {
	r := loadedFake("Enabled")
	r.outputs["-a "+Anchor+" -s rules"] = "block return out quick from any to <leakguard>\n"
	if err := (Firewall{Runner: r}).Apply("", services); err != nil {
		t.Fatalf("Apply(\"\") = %v", err)
	}
	if r.calls[1].args != "-a "+Anchor+" -f -" || r.calls[1].stdin != blockAllRules {
		t.Fatalf("calls = %+v", r.calls)
	}
}

// S7: Verify("") accepts the block rule alone and refuses any pass rule.
func TestStateVerifyWithoutAVPN(t *testing.T) {
	entries := []string{"38.46.212.0/24", "160.79.104.0/23", "2607:6bc0::/48", "203.0.113.0/24", "2001:db8::/32"}
	blockOnly := State{Rules: []string{"block return out quick from any to <leakguard>"}, Entries: entries}
	if err := blockOnly.Verify("", services); err != nil {
		t.Fatalf("Verify(\"\") = %v", err)
	}
	withPass := State{Rules: strings.Split(strings.TrimSpace(loadedRules), "\n"), Entries: entries}
	cases := []struct {
		name  string
		state State
		want  string
	}{
		{"pass rule loaded", withPass, "rules let protected traffic out on an interface"},
		{"nothing loaded", State{}, "not loaded"},
		{"no block rule", State{Rules: withPass.Rules[:1], Entries: entries}, "rules let protected traffic out on an interface"},
		{"missing range", State{Rules: blockOnly.Rules, Entries: entries[1:]}, "range 38.46.212.0/24 of anthropic is not loaded"},
	}
	for _, tc := range cases {
		if err := tc.state.Verify("", services); err == nil || !strings.Contains(err.Error(), tc.want) {
			t.Errorf("%s: Verify(\"\") = %v, want %q", tc.name, err, tc.want)
		}
	}
	// A block-only anchor does not protect a VPN: its pass rule is missing.
	if err := blockOnly.Verify("ipsec0", services); err == nil || !strings.Contains(err.Error(), "pass rule for ipsec0 is not loaded") {
		t.Fatalf("Verify(ipsec0) on block-only rules = %v", err)
	}
}

func TestBlockAllRulesParseWithRealPfctl(t *testing.T) {
	if runtime.GOOS != "darwin" {
		t.Skip("pfctl is only available on macOS")
	}
	if _, err := os.Stat(PfctlPath); err != nil {
		t.Skip("pfctl not found")
	}
	path := filepath.Join(t.TempDir(), "rules.pf")
	os.WriteFile(path, []byte(blockAllRules), 0o644)
	if out, err := exec.Command(PfctlPath, "-n", "-f", path).CombinedOutput(); err != nil {
		t.Fatalf("pfctl -n rejected the block-all rules: %v\n%s", err, out)
	}
}
