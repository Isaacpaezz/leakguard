var services = []catalog.Service{
	{ID: "anthropic", IPv4: []string{"160.79.104.0/23", "38.46.212.0/24"}, IPv6: []string{"2607:6bc0::/48"}},
	{ID: "example", IPv4: []string{"203.0.113.0/24"}, IPv6: []string{"2001:db8::/32"}},
}

func mustRules(t *testing.T, iface string) string {
	t.Helper()
	r, err := Rules(iface, services)
	if err != nil {
		t.Fatalf("Rules(%q) = %v", iface, err)
	}
	return r
}

func TestRules(t *testing.T) {
	got := mustRules(t, "ipsec0")
	want := `# Generated by leakguard. Do not edit; run "leakguard enable" instead.
# Protected services: anthropic, example
table <leakguard> const persist { 160.79.104.0/23, 38.46.212.0/24, 2607:6bc0::/48, 203.0.113.0/24, 2001:db8::/32 }
pass out quick on ipsec0 to <leakguard> keep state
block return out quick to <leakguard>
`
	if got != want {
		t.Fatalf("Rules() =\n%s\nwant\n%s", got, want)
	}
}

func TestRulesParseWithRealPfctl(t *testing.T) {
	if runtime.GOOS != "darwin" {
		t.Skip("pfctl is only available on macOS")
	}
	if _, err := os.Stat(PfctlPath); err != nil {
		t.Skip("pfctl not found")
	}
	// A missing VPN interface must still parse: the block rule has to load
	// while the VPN is down (fail closed).
	path := filepath.Join(t.TempDir(), "rules.pf")
	os.WriteFile(path, []byte(mustRules(t, "utun99")), 0o644)
	out, err := exec.Command(PfctlPath, "-n", "-f", path).CombinedOutput()
	if err != nil {
		t.Fatalf("pfctl -n rejected the rules: %v\n%s", err, out)
	}
}

type call struct {
	args  string
	stdin string
}

type fakeRunner struct {
	calls   []call
	outputs map[string]string
	fail    map[string]error
}

func (f *fakeRunner) Run(stdin string, args ...string) (string, error) {
	key := strings.Join(args, " ")
	f.calls = append(f.calls, call{key, stdin})
	return f.outputs[key], f.fail[key]
}

const loadedRules = `pass out quick on ipsec0 from any to <leakguard> flags S/SA keep state
block return out quick from any to <leakguard>
`
const loadedTable = "   38.46.212.0/24\n   160.79.104.0/23\n   2607:6bc0::/48\n   203.0.113.0/24\n   2001:db8::/32\n"

func loadedFake(pfStatus string) *fakeRunner {
	return &fakeRunner{outputs: map[string]string{
		"-s info":                                "Status: " + pfStatus + " for 0 days\n",
		"-a " + Anchor + " -s rules":             loadedRules,
		"-a " + Anchor + " -t leakguard -T show": loadedTable,
	}}
}

func TestApplyEnablesPfLoadsAnchorAndVerifies(t *testing.T) {
	r := loadedFake("Disabled")
	if err := (Firewall{Runner: r}).Apply("ipsec0", services); err != nil {
		t.Fatalf("Apply() = %v", err)
	}
	var got []string
	for _, c := range r.calls {
		got = append(got, c.args)
	}
	want := "-s info|-E|-a " + Anchor + " -f -|-a " + Anchor + " -s rules|-a " + Anchor + " -t leakguard -T show"
	if strings.Join(got, "|") != want {
		t.Fatalf("calls = %v", got)
	}
	if r.calls[2].stdin != mustRules(t, "ipsec0") {
		t.Fatalf("loaded rules = %q", r.calls[2].stdin)
	}
}

