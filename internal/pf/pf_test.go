func TestStateVerify(t *testing.T) {
	ok := State{Rules: strings.Split(strings.TrimSpace(loadedRules), "\n"), Entries: []string{
		"38.46.212.0/24", "160.79.104.0/23", "2607:6bc0::/48", "203.0.113.0/24", "2001:db8::/32"}}
	if err := ok.Verify("ipsec0", services); err != nil {
		t.Fatalf("Verify() = %v", err)
	}
	cases := []struct {
		name  string
		state State
		iface string
		want  string
	}{
		{"nothing loaded", State{}, "ipsec0", "not loaded"},
		{"other interface", ok, "utun4", "pass rule for utun4"},
		{"no block rule", State{Rules: ok.Rules[:1], Entries: ok.Entries}, "ipsec0", "block rule"},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			if err := tc.state.Verify(tc.iface, services); err == nil || !strings.Contains(err.Error(), tc.want) {
				t.Fatalf("Verify() = %v, want %q", err, tc.want)
			}
		})
	}
}

func TestEnabled(t *testing.T) {
	for _, tc := range []struct {
		status string
		want   bool
	}{{"Enabled", true}, {"Disabled", false}} {
		r := loadedFake(tc.status)
		got, err := (Firewall{Runner: r}).Enabled()
		if err != nil || got != tc.want {
			t.Errorf("Enabled() with %s = %v, %v; want %v", tc.status, got, err, tc.want)
		}
		if len(r.calls) != 1 || r.calls[0].args != "-s info" {
			t.Errorf("calls = %v, want only -s info", r.calls)
		}
	}
	r := &fakeRunner{fail: map[string]error{"-s info": errors.New("Permission denied")}}
	if got, err := (Firewall{Runner: r}).Enabled(); got || err == nil {
		t.Fatalf("Enabled() = %v, %v; want false and the pfctl error", got, err)
	}
}

