// Package pf drives the macOS packet filter. leakguard owns one anchor under
// com.apple/*, which the stock /etc/pf.conf already evaluates, so the system
// configuration is never edited.
package pf

import (
	"bytes"
	"errors"
	"fmt"
	"net/netip"
	"os/exec"
	"strconv"
	"strings"

	"github.com/Isaacpaezz/leakguard/internal/catalog"
	"github.com/Isaacpaezz/leakguard/internal/config"
	"github.com/Isaacpaezz/leakguard/internal/firewall"
)

const (
	// PfctlPath is the absolute path to pfctl; never resolved through $PATH.
	PfctlPath = "/sbin/pfctl"
	// Anchor is the pf anchor that holds every leakguard rule.
	Anchor = "com.apple/250.leakguard"
	// Table is the pf table with the protected ranges.
	Table = "leakguard"
)

// Rules renders the anchor: traffic to the protected ranges may leave only on
// vpnInterface and is rejected on every other interface. The rules load even
// when vpnInterface does not exist, so protection holds with the VPN down.
// An interface name that is not a plain VPN interface is rejected, so it can
// never inject rules or route protected traffic over the real connection.
// An empty vpnInterface renders only the block rule: no interface may carry
// protected traffic.
func Rules(vpnInterface string, services []catalog.Service) (string, error) {
	if vpnInterface != "" {
		if err := config.CheckVPNInterface(vpnInterface); err != nil {
			return "", err
		}
	}
	var ids, ranges []string
	for _, s := range services {
		ids = append(ids, s.ID)
		ranges = append(ranges, s.IPv4...)
		ranges = append(ranges, s.IPv6...)
	}
	var b strings.Builder
	b.WriteString("# Generated by leakguard. Do not edit; run \"leakguard enable\" instead.\n")
	fmt.Fprintf(&b, "# Protected services: %s\n", strings.Join(ids, ", "))
	fmt.Fprintf(&b, "table <%s> const persist { %s }\n", Table, strings.Join(ranges, ", "))
	if vpnInterface != "" {
		fmt.Fprintf(&b, "pass out quick on %s to <%s> keep state\n", vpnInterface, Table)
	}
	fmt.Fprintf(&b, "block return out quick to <%s>\n", Table)
	return b.String(), nil
}

// Runner runs pfctl with the given stdin and arguments.
type Runner interface {
	Run(stdin string, args ...string) (string, error)
}

// ExecRunner runs the real /sbin/pfctl.
type ExecRunner struct{}

// Run implements Runner.
func (ExecRunner) Run(stdin string, args ...string) (string, error) {
	cmd := exec.Command(PfctlPath, args...)
	cmd.Stdin = strings.NewReader(stdin)
	var stdout, stderr bytes.Buffer
	cmd.Stdout, cmd.Stderr = &stdout, &stderr
	if err := cmd.Run(); err != nil {
		return stdout.String(), fmt.Errorf("pfctl %s: %v: %s", strings.Join(args, " "), err, strings.TrimSpace(stderr.String()))
	}
	return stdout.String(), nil
}

// Firewall applies and inspects the leakguard anchor.
type Firewall struct {
	Runner Runner
}

var _ firewall.Firewall = Firewall{}

// Name implements firewall.Firewall.
func (Firewall) Name() string { return "pf" }

// Verify checks that the loaded anchor protects every range of services on
// vpnInterface.
func (f Firewall) Verify(vpnInterface string, services []catalog.Service) error {
	state, err := f.Status()
	if err != nil {
		return err
	}
	return state.Verify(vpnInterface, services)
}

// State is what pf currently has loaded in the anchor.
type State struct {
	Rules   []string
	Entries []string
}

// Apply enables pf if needed, replaces the anchor and verifies the result.
func (f Firewall) Apply(vpnInterface string, services []catalog.Service) error {
	rules, err := Rules(vpnInterface, services)
	if err != nil {
		return err
	}
	enabled, err := f.Enabled()
	if err != nil {
		return err
	}
	// Each "pfctl -E" takes a new enable reference, so only enable when off.
	if !enabled {
		if _, err := f.Runner.Run("", "-E"); err != nil {
			return err
		}
	}
	if _, err := f.Runner.Run(rules, "-a", Anchor, "-f", "-"); err != nil {
		return err
	}
	state, err := f.Status()
	if err != nil {
		return err
	}
	return state.Verify(vpnInterface, services)
}

// Enabled reports whether pf is filtering. Rules in the anchor do nothing
// while pf is disabled.
func (f Firewall) Enabled() (bool, error) {
	info, err := f.Runner.Run("", "-s", "info")
	if err != nil {
		return false, err
	}
	for _, l := range lines(info) {
		if strings.HasPrefix(l, "Status: Enabled") {
			return true, nil
		}
	}
	return false, nil
}

// Flush removes every leakguard rule and table.
func (f Firewall) Flush() error {
	_, err := f.Runner.Run("", "-a", Anchor, "-F", "all")
	return err
}

// Status reads the loaded rules and table entries.
func (f Firewall) Status() (State, error) {
	rules, err := f.Runner.Run("", "-a", Anchor, "-s", "rules")
	if err != nil {
		return State{}, err
	}
	table, err := f.Runner.Run("", "-a", Anchor, "-t", Table, "-T", "show")
	if err != nil {
		// pfctl fails when the table does not exist, which means "not loaded".
		// Any other failure is real and must not look like an empty table.
		if !strings.Contains(strings.ToLower(err.Error()), "table does not exist") {
			return State{}, err
		}
		table = ""
	}
	return State{Rules: lines(rules), Entries: lines(table)}, nil
}

// Verify checks that the state protects every range of services on
// vpnInterface. An empty vpnInterface checks that no interface may carry
// protected traffic: the block rule is loaded and nothing else.
func (s State) Verify(vpnInterface string, services []catalog.Service) error {
	if len(s.Rules) == 0 {
		return ErrNotLoaded
	}
	target := "to <" + Table + ">"
	var pass, block, other bool
	for _, r := range s.Rules {
		other = other || !isBlockRule(r)
		if !strings.Contains(r, target) {
			continue
		}
		pass = pass || vpnInterface != "" && strings.HasPrefix(r, "pass out quick on "+vpnInterface+" ")
		block = block || isBlockRule(r)
	}
	if vpnInterface == "" && other {
		return errors.New("rules let protected traffic out on an interface; they should block it on every interface")
	}
	if !pass && vpnInterface != "" {
		return fmt.Errorf("pass rule for %s is not loaded", vpnInterface)
	}
	if !block {
		return fmt.Errorf("block rule is not loaded")
	}
	loaded := map[netip.Prefix]bool{}
	for _, e := range s.Entries {
		if p, ok := parseEntry(e); ok {
			loaded[p] = true
		}
	}
	for _, svc := range services {
		for _, r := range append(append([]string{}, svc.IPv4...), svc.IPv6...) {
			p, err := netip.ParsePrefix(r)
			if err != nil || !loaded[p.Masked()] {
				return fmt.Errorf("range %s of %s is not loaded", r, svc.ID)
			}
		}
	}
	return nil
}

// parseEntry reads one "pfctl -T show" line. pfctl prints single hosts
// without a prefix length and may format IPv6 differently from the catalog.
func parseEntry(e string) (netip.Prefix, bool) {
	if strings.Contains(e, "/") {
		p, err := netip.ParsePrefix(e)
		return p.Masked(), err == nil
	}
	a, err := netip.ParseAddr(e)
	if err != nil {
		return netip.Prefix{}, false
	}
	return netip.PrefixFrom(a, a.BitLen()), true
}

func lines(s string) []string {
	var out []string
	for _, l := range strings.Split(s, "\n") {
		if l = strings.TrimSpace(l); l != "" {
			out = append(out, l)
		}
	}
	return out
}

// ErrNotLoaded means the anchor has no rules, so there is no counter.
var ErrNotLoaded = firewall.ErrNotLoaded

// BlockCount returns how many packets the block rule has rejected since the
// anchor was last loaded: pf resets the counter on every reload or flush.
// Any output it cannot read is an error, never a zero: a fake zero would
// look like a reset and hide or invent blocks.
func (f Firewall) BlockCount() (uint64, error) {
	out, err := f.Runner.Run("", "-a", Anchor, "-s", "rules", "-v")
	if err != nil {
		return 0, err
	}
	return parseBlockCount(out)
}

// parseBlockCount adds the Packets counters of the block rules in the output
// of "pfctl -s rules -v", which prints each rule's counters on the next line:
//
//	block return out quick from any to <leakguard>
//	  [ Evaluations: 120       Packets: 14        Bytes: 840         States: 0     ]
func parseBlockCount(out string) (uint64, error) {
	ls := lines(out)
	if len(ls) == 0 {
		return 0, ErrNotLoaded
	}
	var total uint64
	found := false
	for i, l := range ls {
		if !isBlockRule(l) {
			continue
		}
		found = true
		if i+1 >= len(ls) || !strings.HasPrefix(ls[i+1], "[") {
			return 0, errors.New("cannot read the block counter: no counters after the block rule")
		}
		n, ok := packets(ls[i+1])
		if !ok {
			return 0, fmt.Errorf("cannot read the block counter: no packet count in %q", ls[i+1])
		}
		total += n
	}
	if !found {
		return 0, errors.New("block rule is not loaded")
	}
	return total, nil
}

func isBlockRule(rule string) bool {
	return strings.HasPrefix(rule, "block return out quick ") && strings.Contains(rule, "to <"+Table+">")
}

// packets reads the number after "Packets:" in a counters line.
func packets(counters string) (uint64, bool) {
	f := strings.Fields(counters)
	for i := 0; i+1 < len(f); i++ {
		if f[i] == "Packets:" {
			n, err := strconv.ParseUint(f[i+1], 10, 64)
			return n, err == nil
		}
	}
	return 0, false
}
